import type { NextConfig } from "next";

// Cache Components is off: almost every CastleHub page reads the session or
// fresh rows, so the previous dynamic-rendering model is simpler here.
const nextConfig: NextConfig = {
  devIndicators: false,
  // Basic hardening: no framing (clickjacking), no MIME sniffing, no full-URL referrers.
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Content-Security-Policy", value: "frame-ancestors 'none'" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(self), geolocation=()" },
        ],
      },
    ];
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
